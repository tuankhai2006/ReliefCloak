const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'relief-governance-'))
const load = require('./service-test-loader.cjs')(directory)
const s = load('services/reliefService'), community = load('services/communityService'), store = load('models/reliefStore')
const admin = { id: 'org', name: 'Admin', roles: ['org_admin'] }
const auditor = { id: 'aud', name: 'Auditor', roles: ['auditor'] }
const officer = { id: 'off', name: 'Officer', roles: ['disburser'] }
const user = { id: 'user', name: 'Resident', roles: ['appUser'] }
const fail = (fn, status, message) => assert.throws(fn, e => e.status === status && (!message || e.message === message))
try {
  // Preserve pre-existing community data while moving to the common store.
  fs.writeFileSync(path.join(directory, 'community.json'), JSON.stringify({ reports: [{ id: 'legacy', createdBy: 'user', region: 'Legacy', description: 'private', createdAt: new Date().toISOString() }], posts: [] }))
  assert.equal(community.reportsFor(user).length, 1)
  fail(() => s.adminSnapshot(user), 403)
  const report = community.submitReport(user, { region: 'Hue', description: 'PRIVATE MEDICAL DETAILS', status: 'ACCEPTED' })
  assert.equal(report.status, 'NEW')
  fail(() => s.reviewReport(auditor, report.id, { status: 'VERIFYING', feedback: 'review' }), 403)
  fail(() => s.reviewReport(admin, report.id, { status: 'ACCEPTED', feedback: 'skip' }), 409)
  s.reviewReport(admin, report.id, { status: 'VERIFYING', feedback: 'checking' })
  s.reviewReport(admin, report.id, { status: 'ACCEPTED', feedback: 'verified demo' })
  assert.equal(community.reportsFor(user).length, 2)
  const fields = { reportId: report.id, title: { vi: 'Huế', en: 'Hue' }, content: { vi: 'Công khai', en: 'Public' }, targetVnd: 1000, image: '/photos/flood-1.svg' }
  fail(() => s.createCampaign(user, fields), 403)
  fail(() => s.createCampaign(admin, { ...fields, image: 'https://untrusted.invalid/image' }), 400)
  const c = s.createCampaign(admin, fields)
  assert.equal(s.publicCampaigns().length, 0)
  fail(() => s.createCampaign(admin, fields), 409)
  s.updateCampaign(admin, c.id, { action: 'save', ...fields })
  s.updateCampaign(admin, c.id, { action: 'publish' })
  fail(() => s.updateCampaign(admin, c.id, { action: 'save', ...fields }), 409)
  for (const amountVnd of [0, -1, 1.2, '200', Number.MAX_SAFE_INTEGER]) fail(() => s.recordDonation(user, { campaignId: c.id, amountVnd, anonymous: true, idempotencyKey: 'bad' }), 400)
  const donationBody = { campaignId: c.id, amountVnd: 1000, anonymous: true, idempotencyKey: 'donation-1' }
  const donation = s.recordDonation(user, donationBody)
  assert.equal(s.recordDonation(user, donationBody).id, donation.id)
  fail(() => s.recordDonation(user, { ...donationBody, amountVnd: 999 }), 409)
  assert.equal(s.ownDonations(user).length, 1)
  assert.equal(s.ownDonations(auditor).length, 0)
  const proposal = { campaignId: c.id, amountVnd: 700, purpose: 'PRIVATE purpose', recipient: 'PRIVATE recipient' }
  fail(() => s.proposeDisbursement(auditor, proposal), 403)
  fail(() => s.proposeDisbursement(admin, { ...proposal, amountVnd: 1001 }), 409)
  const first = s.proposeDisbursement(admin, proposal)
  const second = s.proposeDisbursement(admin, proposal)
  fail(() => s.executeDisbursement(officer, first.id, { idempotencyKey: 'exec1' }), 409)
  fail(() => s.decideDisbursement({ ...admin, roles: ['org_admin', 'auditor'] }, first.id, { decision: 'APPROVED', note: 'self approval' }), 403)
  s.decideDisbursement(auditor, first.id, { decision: 'APPROVED', note: 'PRIVATE audit note', amountVnd: 1 })
  assert.equal(store.readRelief().disbursements.find(d => d.id === first.id).amountVnd, 700)
  fail(() => s.executeDisbursement({ ...auditor, roles: ['auditor', 'disburser'] }, first.id, { idempotencyKey: 'exec1' }), 403)
  s.decideDisbursement(auditor, second.id, { decision: 'APPROVED', note: 'checked' })
  s.executeDisbursement(officer, first.id, { idempotencyKey: 'exec1' })
  const auditCount = store.readRelief().audit.length
  s.executeDisbursement(officer, first.id, { idempotencyKey: 'exec1' })
  assert.equal(store.readRelief().audit.length, auditCount)
  fail(() => s.executeDisbursement(officer, first.id, { idempotencyKey: 'different' }), 409)
  fail(() => s.executeDisbursement(officer, second.id, { idempotencyKey: 'exec2' }), 409, 'INSUFFICIENT_FUNDS')
  assert.equal(s.publicCampaigns()[0].availableVnd, 300)
  const third = s.proposeDisbursement(admin, { ...proposal, amountVnd: 100 })
  s.decideDisbursement(auditor, third.id, { decision: 'REJECTED', note: 'not supported' })
  fail(() => s.executeDisbursement(officer, third.id, { idempotencyKey: 'exec3' }), 409)
  const publicData = JSON.stringify(s.transparency())
  assert.equal(publicData.includes('PRIVATE'), false)
  for (const key of ['donorId', 'createdBy', 'recipient', 'idempotencyKey', 'auditNote']) assert.equal(publicData.includes('"' + key + '"'), false)
  assert.equal(s.adminSnapshot(auditor).reports.length, 0)
  s.updateCampaign(admin, c.id, { action: 'close' })
  fail(() => s.recordDonation(user, { ...donationBody, idempotencyKey: 'new-after-close' }), 409)
  assert.equal(s.recordDonation(user, donationBody).id, donation.id)
  // Concurrent workers cannot mutate during another worker's transaction.
  fs.mkdirSync(path.join(directory, 'relief.lock'))
  const before = fs.readFileSync(path.join(directory, 'relief.json'), 'utf8')
  fail(() => community.submitReport(user, { region: 'X', description: 'Y' }), 409, 'STORE_BUSY')
  assert.equal(fs.readFileSync(path.join(directory, 'relief.json'), 'utf8'), before)
  fs.rmdirSync(path.join(directory, 'relief.lock'))
  console.log('PASS: migration, role boundaries, report transitions, campaign lifecycle, donation idempotency, independent approval, immutable payloads, payout replay, overspending, rejection, privacy, storage contention')
} finally { fs.rmSync(directory, { recursive: true, force: true }) }
